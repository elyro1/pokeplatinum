#!/usr/bin/env python3
"""Build a Windows executable on Linux using native assets and MinGW.

Meson's desktop targets currently mark both tools and game libraries native.
Reuse its Linux build graph for generators, source lists, defines and archive
ordering, then emit a separate Ninja graph for Windows objects and libraries.
No Linux objects or libraries are linked into the Windows executable.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tarfile


ROOT = Path(__file__).resolve().parents[2]
TRIPLET = 'x86_64-w64-mingw32'


def run(args, **kwargs):
    print('+', shlex.join(map(str, args)), flush=True)
    return subprocess.run(list(map(str, args)), check=True, **kwargs)


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def prepare_dependencies(build, jobs):
    deps = build / 'local-deps'
    sources = deps / 'sources'
    downloads = deps / 'downloads'
    prefix = deps / 'prefix'
    downloads.mkdir(parents=True, exist_ok=True)
    packages = [
        ('SDL2-devel-2.32.10-mingw.tar.gz',
         'https://www.libsdl.org/release/SDL2-devel-2.32.10-mingw.tar.gz', 'SDL2-2.32.10',
         '83a5d74012311edc3c0d40ea6faecbe57ad692aa033fa5dc273cc937e3938ff2'),
        ('enet-1.3.18.tar.gz',
         'https://github.com/lsalzman/enet/archive/refs/tags/v1.3.18.tar.gz', 'enet-1.3.18',
         '28603c895f9ed24a846478180ee72c7376b39b4bb1287b73877e5eae7d96b0dd'),
        ('soundtouch-2.3.3.tar.gz',
         'https://www.surina.net/soundtouch/soundtouch-2.3.3.tar.gz', 'soundtouch',
         '43b23dfac2f64a3aff55d64be096ffc7b73842c3f5665caff44975633a975a99'),
    ]
    for filename, url, directory, digest in packages:
        archive = downloads / filename
        if not archive.exists():
            temporary = archive.with_suffix('.partial')
            run(['curl', '--fail', '--location', '--retry', '2', '-o', temporary, url])
            temporary.rename(archive)
        if hashlib.sha256(archive.read_bytes()).hexdigest() != digest:
            raise RuntimeError('Download checksum mismatch: ' + str(archive))
        if not (sources / directory).exists():
            with tarfile.open(archive) as contents:
                contents.extractall(sources, filter='data')
    for name, directory, options in [
        ('enet', 'enet-1.3.18', ['-DENET_BUILD_TESTS=OFF']),
        ('soundtouch', 'soundtouch', ['-DSOUNDSTRETCH=OFF', '-DSOUNDTOUCH_DLL=OFF']),
    ]:
        output = deps / (name + '-build')
        run(['cmake', '-S', sources / directory, '-B', output, '-G', 'Ninja',
             '-DCMAKE_SYSTEM_NAME=Windows', '-DCMAKE_BUILD_TYPE=Release',
             '-DCMAKE_C_COMPILER=' + TRIPLET + '-gcc',
             '-DCMAKE_CXX_COMPILER=' + TRIPLET + '-g++',
             '-DCMAKE_INSTALL_PREFIX=' + str(prefix), '-DBUILD_SHARED_LIBS=OFF',
             '-DCMAKE_POLICY_VERSION_MINIMUM=3.5', *options])
        run(['cmake', '--build', output, '--parallel', jobs])
        run(['cmake', '--install', output])
    # nanotime.h uses the case-insensitive Windows spelling of this SDK header.
    write_if_changed(prefix / 'include/Windows.h', '#include <windows.h>\n')
    return sources / 'SDL2-2.32.10' / TRIPLET, prefix


def ninja_path(path):
    return str(path).replace('$', '$$').replace(' ', '$ ').replace(':', '$:')


def ninja_command(args):
    return shlex.join(map(str, args)).replace('$', '$$')


def generate_build(native, output, sdl, prefix):
    entries = json.loads((native / 'compile_commands.json').read_text())
    # Ask Ninja to expand response files rather than parsing Meson's linker flags.
    commands = json.loads(subprocess.check_output(
        ['ninja', '-C', str(native), '-t', 'compdb', '-x', 'cpp_LINKER_FOR_BUILD_RSP'], text=True))
    link = next(shlex.split(e['command']) for e in commands if e['output'] == 'main')
    archives = {arg for arg in link if arg.endswith('.a')}
    archive_objects = {}
    for line in (native / 'build.ninja').read_text().splitlines():
        if not line.startswith('build ') or ': STATIC_LINKER' not in line:
            continue
        name, inputs = line[6:].split(': ', 1)
        if name in archives:
            archive_objects[name] = inputs.split()[1:]
    if set(archive_objects) != archives:
        raise RuntimeError('Unsupported archive layout in native build graph')
    wanted = {arg for arg in link if arg.endswith('.o')}
    for objects in archive_objects.values():
        wanted.update(objects)
    icon = 'main.p/src_port_sim_icon.cpp.o'
    wanted.discard(icon)  # This source is enabled only for Linux in src/meson.build.
    lines = [
        '# Generated by tools/scripts/build_mingw.py; Windows objects only.',
        'rule compile', '  command = $command',
        '  depfile = $out.d', '  deps = gcc', '  description = MinGW $out',
        'rule archive', f'  command = {TRIPLET}-ar rcs $out $in',
        '  description = Archiving $out',
        'rule link', '  command = ' + TRIPLET + '-g++ @$out.rsp',
        '  rspfile = $out.rsp', '  rspfile_content = $args',
        '  description = Linking $out',
    ]
    compiled = set()
    for entry in entries:
        dest = entry['output']
        if dest not in wanted:
            continue
        args = shlex.split(entry['command'])
        args[0] = TRIPLET + ('-g++' if args[0].endswith('++') else '-gcc')
        converted = [args[0]]
        i = 1
        while i < len(args):
            arg = args[i]
            if arg in ('-o', '-MF', '-MQ'):
                i += 2
                continue
            if arg in ('-MD', '-fpch-preprocess', '-fPIC', '-fPIE'):
                i += 1
                continue
            if arg == '-include':
                header = args[i + 1]
                if header == 'global_pch.h':
                    header = str(ROOT / 'include/pch/global_pch.h')
                elif header == 'nitro_pch.h':
                    header = str(ROOT / 'subprojects/libntr/include/pch/nitro_pch.h')
                elif not Path(header).is_absolute():
                    header = str((native / header).resolve())
                converted.extend(['-include', header])
                i += 2
                continue
            if arg.startswith('-I'):
                directory = Path(arg[2:])
                if directory.is_absolute() and str(directory).startswith('/usr/'):
                    i += 1
                    continue
                arg = '-I' + str((native / directory).resolve())
            elif not arg.startswith('-'):
                arg = str((native / arg).resolve())
            converted.append(arg.replace('-DSDK_BUILD_LINUX', '-DSDK_BUILD_WIN64'))
            i += 1
        # libntr's filesystem uses tolower without including ctype.h itself.
        converted.extend(['-include', 'ctype.h',
                          '-I' + str(sdl / 'include'), '-I' + str(sdl / 'include/SDL2'),
                          '-I' + str(prefix / 'include'), '-I' + str(prefix / 'include/soundtouch'),
                          '-Werror=incompatible-pointer-types' if args[0].endswith('-gcc') else '-Werror',
                          '-MD', '-MF', dest + '.d', '-o', dest])
        if entry['file'].endswith('/sim/src/g3_handler.cpp'):
            # The simulator currently relies on another header declaring sqrtf.
            converted.extend(['-include', 'math.h'])
        (output / dest).parent.mkdir(parents=True, exist_ok=True)
        source = str((native / entry['file']).resolve())
        lines.extend([f'build {ninja_path(dest)}: compile {ninja_path(source)}',
                      '  command = ' + ninja_command(converted)])
        compiled.add(dest)
    missing = wanted - compiled - {'trainer_ai_script.o'}
    if missing:
        raise RuntimeError('Missing compilation commands: ' + ', '.join(sorted(missing)))
    # The native preprocessor produced platform-independent assembly data.
    lines.extend(['build trainer_ai_script.o: compile ' + ninja_path(native / 'trainer_ai_script.ss'),
                  '  command = ' + ninja_command([TRIPLET + '-as', '-I', ROOT / 'asm',
                      '-I', native, '-o', 'trainer_ai_script.o', native / 'trainer_ai_script.ss'])])
    for name, objects in archive_objects.items():
        (output / name).parent.mkdir(parents=True, exist_ok=True)
        lines.append(f'build {ninja_path(name)}: archive ' + ' '.join(map(ninja_path, objects)))
    args = []
    for arg in link[1:]:
        if arg == icon or arg == '-Wl,--as-needed':
            continue
        if arg == 'main':
            arg = 'main.exe'
        elif arg == '-lSDL2':
            arg = str(sdl / 'lib/libSDL2.dll.a')
        elif arg == '-lenet':
            arg = str(prefix / 'lib/static/libenet.a')
        elif 'libSoundTouch.so' in arg:
            arg = str(prefix / 'lib/libSoundTouch.a')
        elif arg.startswith('/usr/'):
            raise RuntimeError('Unexpected native library in Windows link: ' + arg)
        args.append(arg)
    args.extend(['-static-libgcc', '-static-libstdc++', '-Wl,-Bstatic', '-lwinpthread',
                 '-Wl,-Bdynamic', '-lws2_32', '-lwinmm', '-lshlwapi', '-lcomdlg32', '-lole32'])
    inputs = sorted(wanted | archives)
    lines.extend(['build main.exe: link ' + ' '.join(map(ninja_path, inputs)),
                  '  args = ' + ninja_command(args), 'default main.exe'])
    write_if_changed(output / 'build.ninja', '\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('-j', '--jobs', type=int, default=min(os.cpu_count() or 2, 8))
    parser.add_argument('--native-build', type=Path, default=ROOT / 'build_linux')
    parser.add_argument('--build', type=Path, default=ROOT / 'build_win64')
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error('--jobs must be positive')
    native, build = args.native_build.resolve(), args.build.resolve()
    os.chdir(ROOT)
    run(['make', 'linux', 'BUILD_LINUX=' + str(native)])
    sdl, prefix = prepare_dependencies(build, args.jobs)
    output = build / 'mingw'
    output.mkdir(parents=True, exist_ok=True)
    generate_build(native, output, sdl, prefix)
    run(['ninja', '-C', output, '-j', args.jobs])
    release = build / 'pokeplatinum/release_win64'
    release.mkdir(parents=True, exist_ok=True)
    for source in [output / 'main.exe', sdl / 'bin/SDL2.dll',
                   native / 'pokeplatinum/firmware.bin', native / 'pokeplatinum/header.bin']:
        shutil.copy2(source, release / source.name)
    print('Windows build:', release / 'main.exe')


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print('MinGW build failed:', error, file=sys.stderr)
        sys.exit(1)
